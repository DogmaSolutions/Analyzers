using System.Threading.Tasks;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Testing;
using Microsoft.VisualStudio.TestTools.UnitTesting;

// ReSharper disable All
#pragma warning disable CA1062 // test parameters come from DynamicData

namespace DogmaSolutions.Analyzers.Test;

public partial class DSA044Tests
{
    [TestMethod]
    public async Task The_message_tells_the_call_and_the_logger()
    {
        var source = BuildClass(string.Empty, Header, "private readonly ILogger<Service> _logger;\npublic void Run(int x) { [[Console.Error.WriteLine(\"hello {0}\", x)]]; }", matched: true);
        var test = CreateTest(source, string.Empty);
        test.ExpectedDiagnostics.Add(
            CSharpAnalyzerVerifier<DSA044Analyzer>.Diagnostic(DSA044Analyzer.DiagnosticId).WithLocation(0).WithArguments("Console.Error.WriteLine", "_logger"));

        await test.RunAsync().ConfigureAwait(false);
    }

    [TestMethod]
    public async Task Every_call_is_reported()
    {
        const string members = "private ILogger _logger;\npublic void Run() { {|#0:Console.WriteLine(\"a\")|}; {|#1:Debug.WriteLine(\"b\")|}; Console.Beep(); {|#2:Console.Write(\"c\")|}; }";
        var test = CreateTest(DSA044TestSupport.Usings + "namespace TestApp\n{\n    public class Service\n    {\n" + members + "\n    }\n}", string.Empty);
        for (var i = 0; i < 3; i++)
            test.ExpectedDiagnostics.Add(new DiagnosticResult(DSA044Analyzer.DiagnosticId, DiagnosticSeverity.Info).WithLocation(i));

        await test.RunAsync().ConfigureAwait(false);
    }

    [TestMethod]
    public async Task A_logger_declared_in_another_part_of_a_partial_class_is_available()
    {
        var first = BuildClass(string.Empty, "public partial class Service", "public void Run() { [[Console.WriteLine(\"hello\")]]; }", matched: true);
        var test = CreateTest(first, string.Empty);
        test.TestState.Sources.Add(("/0/Second.cs", "namespace TestApp\n{\n    public partial class Service\n    {\n        private Microsoft.Extensions.Logging.ILogger _logger;\n    }\n}"));
        ExpectDiagnostic(test);

        await test.RunAsync().ConfigureAwait(false);
    }

    [TestMethod]
    public async Task A_static_logger_called_in_another_part_of_a_partial_class_is_available()
    {
        var first = BuildClass(string.Empty, "public partial class Service", "public void Run() { [[Console.WriteLine(\"hello\")]]; }", matched: true);
        var test = CreateTest(first, string.Empty);
        test.TestState.Sources.Add(("/0/Second.cs", "namespace TestApp\n{\n    public partial class Service\n    {\n        public void Other() { Serilog.Log.Information(\"x\"); }\n    }\n}"));
        ExpectDiagnostic(test);

        await test.RunAsync().ConfigureAwait(false);
    }

    [TestMethod]
    public async Task A_call_that_cannot_be_resolved_is_ignored()
    {
        const string source = "using Microsoft.Extensions.Logging;\nnamespace TestApp\n{\n    public class Service\n    {\n        private ILogger _l;\n        public void Run() { {|CS0103:Unknown|}.WriteLine(\"hello\"); }\n    }\n}";
        var test = CreateTest(source, string.Empty);

        await test.RunAsync().ConfigureAwait(false);
    }

    [TestMethod]
    public async Task Nothing_is_reported_without_a_logger_type_in_the_compilation()
    {
        var test = new CSharpAnalyzerVerifier<DSA044Analyzer>.Test();
        test.TestCode = "using System;\nnamespace TestApp\n{\n    public class Service\n    {\n        public void Run() { Console.WriteLine(\"hello\"); }\n    }\n}";
        test.ReferenceAssemblies = ReferenceAssemblies.Net.Net80;

        await test.RunAsync().ConfigureAwait(false);
    }

    [TestMethod]
    public async Task Generated_code_is_not_analyzed()
    {
        var source = "// <auto-generated/>\n" + BuildClass(string.Empty, Header, "private ILogger _l;\npublic void Run() { [[Console.WriteLine(\"hello\")]]; }", matched: false);
        var test = CreateTest(source, string.Empty);

        await test.RunAsync().ConfigureAwait(false);
    }

    [TestMethod]
    public async Task A_file_matching_an_excluded_pattern_is_skipped_and_another_is_not()
    {
        const string members = "private ILogger _l;\npublic void Run() { Console.WriteLine(\"hello\"); }";
        var skipped = CreateTest("namespace TestApp { }", "excluded_file_patterns=*.skip.cs");
        skipped.TestState.Sources.Add(("/0/Service.skip.cs", BuildClass(string.Empty, Header, members, matched: false)));
        await skipped.RunAsync().ConfigureAwait(false);

        var reported = CreateTest("namespace TestApp { }", string.Empty);
        reported.TestState.Sources.Add(("/0/Service.skip.cs", BuildClass(string.Empty, Header, members.Replace("Console.WriteLine(\"hello\")", "[[Console.WriteLine(\"hello\")]]"), matched: true)));
        ExpectDiagnostic(reported);
        await reported.RunAsync().ConfigureAwait(false);
    }
}
