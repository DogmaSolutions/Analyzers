namespace DogmaSolutions.Analyzers.Test;

public partial class DSA043Tests
{
    [TestMethod]
    public async Task The_message_tells_the_class_the_complexity_and_the_lines()
    {
        var test = CreateTest(BuildClass(string.Empty, "public class [[Service]]", string.Empty, Catch, expectDiagnostic: true), string.Empty);
        test.ExpectedDiagnostics.Add(
            CSharpAnalyzerVerifier<DSA043Analyzer>.Diagnostic(DSA043Analyzer.DiagnosticId).WithLocation(0).WithArguments("Service", 6, 12));

        await test.RunAsync().ConfigureAwait(false);
    }

    [TestMethod]
    public async Task Nothing_is_reported_when_the_compilation_has_no_logging_type()
    {
        var test = CreateTest(BuildClass(string.Empty, "public class [[Service]]", string.Empty, Catch, expectDiagnostic: false).Replace("using Microsoft.Extensions.Logging;\n", string.Empty), string.Empty, withLoggingReference: false);

        await test.RunAsync().ConfigureAwait(false);
    }

    [TestMethod]
    public async Task A_configured_logger_type_that_exists_makes_the_rule_apply()
    {
        var test = CreateTest(
            BuildClass(string.Empty, "public class [[Service]]", string.Empty, Catch, expectDiagnostic: true).Replace("using Microsoft.Extensions.Logging;\n", string.Empty),
            "logger_namespaces=Nothing.Here;logger_types=MyCompany.Diagnostics.IAppLogger");
        ExpectDiagnostic(test);

        await test.RunAsync().ConfigureAwait(false);
    }

    [TestMethod]
    public async Task A_nested_type_is_skipped_unless_included()
    {
        const string members = "public class Inner { public int Run(int x) { if (x == 1) { x++; } if (x == 2) { x++; } if (x == 3) { x++; } try { x++; } catch (System.Exception) { x--; } return x; } }";
        var source = "using Microsoft.Extensions.Logging;\nnamespace TestApp\n{\n    public class Outer\n    {\n        " + members + "\n    }\n}";
        var skipped = CreateTest(source, string.Empty);
        await skipped.RunAsync().ConfigureAwait(false);

        var included = CreateTest(source.Replace("public class Inner", "public class {|#0:Inner|}"), "include_nested_types=true");
        ExpectDiagnostic(included);
        await included.RunAsync().ConfigureAwait(false);
    }

    [TestMethod]
    public async Task The_parts_of_a_partial_class_are_measured_together_and_the_first_one_is_reported()
    {
        const string part = "    public partial class {0}\n    {{\n        public int {1}(int x)\n        {{\n            if (x == 1) {{ x++; }}\n            if (x == 2) {{ x++; }}\n            try {{ x++; }} catch (System.Exception) {{ x--; }}\n            return x;\n        }}\n    }}\n";
        var first = "namespace TestApp\n{\n" + string.Format(System.Globalization.CultureInfo.InvariantCulture, part, "{|#0:Service|}", "First") + "}";
        var second = "namespace TestApp\n{\n" + string.Format(System.Globalization.CultureInfo.InvariantCulture, part, "Service", "Second") + "}";

        // each part alone has a complexity of 4: the 6 needed to be reported are only reached by the two together
        var test = CreateTest(first, "min_cyclomatic_complexity=6;min_method_complexity=0;min_lines=0");
        test.TestState.Sources.Add(("/0/Second.cs", second));
        ExpectDiagnostic(test);

        await test.RunAsync().ConfigureAwait(false);
    }

    [TestMethod]
    [DataRow("Service.Designer.cs", "")]
    [DataRow("Service.generated.cs", "")]
    [DataRow("Service.g.cs", "")]
    [DataRow("Service.skip.cs", "excluded_file_patterns=*.skip.cs")]
    public async Task A_class_in_an_excluded_file_is_skipped(string fileName, string settings)
    {
        var test = CreateTest("namespace TestApp { }", settings);
        test.TestState.Sources.Add(("/0/" + fileName, BuildClass(string.Empty, "public class [[Service]]", string.Empty, Catch, expectDiagnostic: false)));

        await test.RunAsync().ConfigureAwait(false);
    }

    [TestMethod]
    public async Task A_class_in_a_file_that_is_not_excluded_is_reported()
    {
        var test = CreateTest("namespace TestApp { }", string.Empty);
        test.TestState.Sources.Add(("/0/Other.cs", BuildClass(string.Empty, "public class [[Service]]", string.Empty, Catch, expectDiagnostic: true)));
        ExpectDiagnostic(test);

        await test.RunAsync().ConfigureAwait(false);
    }

    [TestMethod]
    public async Task Generated_code_is_not_analyzed()
    {
        var source = "// <auto-generated/>\n" + BuildClass(string.Empty, "public class [[Service]]", string.Empty, Catch, expectDiagnostic: false);
        var test = CreateTest(source, string.Empty);

        await test.RunAsync().ConfigureAwait(false);
    }

    [TestMethod]
    public async Task Interfaces_enums_and_delegates_are_never_looked_at()
    {
        const string source = "namespace TestApp\n{\n    public interface IThing { int Run(int x); }\n    public enum Kind { A, B }\n    public delegate void Handler(int x);\n}";
        var test = CreateTest(source, string.Empty);

        await test.RunAsync().ConfigureAwait(false);
    }

    [TestMethod]
    public async Task The_real_logging_package_is_recognized()
    {
        var withLogger = BuildClass(string.Empty, "public class [[Service]]", "private readonly ILogger<Service> _logger;", Catch, expectDiagnostic: false);
        var withoutLogger = BuildClass(string.Empty, "public class [[Service]]", string.Empty, Catch, expectDiagnostic: true);

        foreach (var (source, reported) in new[] { (withLogger, false), (withoutLogger, true) })
        {
            var test = new CSharpAnalyzerVerifier<DSA043Analyzer>.Test();
            test.TestCode = source;
            test.ReferenceAssemblies = ReferenceAssemblies.Net.Net80.AddPackages(ImmutableArray.Create(new PackageIdentity("Microsoft.Extensions.Logging.Abstractions", "8.0.0")));
            test.TestState.AnalyzerConfigFiles.Add(("/.editorconfig", ToEditorConfig(string.Empty)));
            if (reported)
                ExpectDiagnostic(test);

            await test.RunAsync().ConfigureAwait(false);
        }
    }
}
